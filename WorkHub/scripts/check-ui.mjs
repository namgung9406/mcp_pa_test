import { chromium } from '@playwright/test';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, locale: 'ko-KR' });
const errors = [];
const remote = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (/^https?:/.test(request.url())) remote.push(request.url()); });
const url = pathToFileURL(resolve('dist/WorkHub-미리보기.html')).href;
const checks = [];
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); };
try {
  await page.goto(url);
  await page.getByRole('heading', { name: '통합 대시보드.' }).waitFor();
  await page.locator('.wh-kpi').first().waitFor();
  check('통합 대시보드 24건 집계', (await page.locator('.wh-kpi').first().innerText()).includes('24'));
  await page.screenshot({ path: 'test-results/01-dashboard.png' });
  const nav = page.getByRole('navigation', { name: '주 메뉴' });
  await nav.getByRole('button', { name: '전체 업무', exact: true }).click();
  check('전체 업무 페이지당 8행', await page.locator('tbody tr').count() === 8);
  await page.getByRole('button', { name: '다음 페이지' }).click();
  check('목록 페이지 이동', (await page.locator('.wh-pagination').innerText()).includes('9–16'));
  await page.getByRole('textbox', { name: '업무 검색' }).fill('고객 온보딩');
  check('검색 결과 1건', await page.locator('tbody tr').count() === 1);
  await page.locator('.wh-task-link').first().click();
  await page.getByRole('dialog', { name: '업무 상세' }).waitFor();
  await page.screenshot({ path: 'test-results/02-project-detail.png' });
  await page.getByRole('combobox', { name: '상태 변경' }).selectOption('완료');
  await page.getByRole('button', { name: '활동 기록', exact: false }).click();
  await page.getByText('진행 중 → 완료', { exact: true }).waitFor();
  check('상태 변경 로그', true);
  await page.getByRole('textbox', { name: '댓글 입력' }).fill('시연 결과 확인 완료했습니다.');
  await page.getByRole('button', { name: '댓글 등록' }).click();
  await page.getByText('시연 결과 확인 완료했습니다.', { exact: true }).waitFor();
  check('댓글 등록과 기록 연결', true);
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await nav.getByRole('button', { name: '구매·지출', exact: true }).click();
  await page.screenshot({ path: 'test-results/03-purchases.png' });
  await page.getByRole('button', { name: '새 업무 등록', exact: true }).click();
  await page.getByLabel('업무명', { exact: false }).fill('시연용 모니터 구매');
  await page.getByLabel('업무 설명', { exact: false }).fill('신규 프로젝트 시연을 위한 모니터를 구매합니다.');
  await page.getByLabel('요청 금액 (원)', { exact: false }).fill('2400000');
  await page.getByLabel('거래처', { exact: false }).fill('가상 데모 공급사');
  await page.getByRole('button', { name: '업무 등록', exact: true }).click();
  await page.getByRole('heading', { name: '시연용 모니터 구매', exact: true }).waitFor();
  check('구매 요청 등록', (await page.locator('.wh-purchase-card').innerText()).includes('2,400,000'));
  await page.getByRole('combobox', { name: '상태 변경' }).selectOption('검토 중');
  await page.getByRole('button', { name: '승인 완료 (데모)', exact: true }).click();
  await page.locator('.wh-detail-title .wh-badge').filter({ hasText: '완료' }).waitFor();
  await page.screenshot({ path: 'test-results/04-purchase-detail.png' });
  check('구매 승인 데모', true);
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await nav.getByRole('button', { name: 'IT 서비스', exact: true }).click();
  await page.getByRole('button', { name: '새 업무 등록', exact: true }).click();
  await page.getByLabel('업무명', { exact: false }).fill('사내 VPN 연결 오류');
  await page.getByLabel('업무 설명', { exact: false }).fill('외부 근무 시 VPN 연결이 반복적으로 끊기는 현상입니다.');
  await page.getByLabel('대상 서비스', { exact: false }).fill('VPN');
  await page.getByLabel('영향 범위').selectOption('전사');
  await page.getByRole('button', { name: '업무 등록', exact: true }).click();
  await page.getByRole('heading', { name: '사내 VPN 연결 오류', exact: true }).waitFor();
  check('IT 서비스 전용 필드', (await page.locator('.wh-domain-info').innerText()).includes('전사'));
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await nav.getByRole('button', { name: '통합 대시보드', exact: true }).click();
  check('신규 업무 대시보드 반영', (await page.locator('.wh-kpi').first().innerText()).includes('26'));
  await nav.getByRole('button', { name: '활동 로그', exact: true }).click();
  await page.getByRole('combobox', { name: '활동 유형' }).selectOption('댓글');
  check('활동 유형 필터', await page.locator('.wh-timeline-entry').count() === 1);
  await page.getByRole('combobox', { name: '활동 유형' }).selectOption('전체');
  await page.screenshot({ path: 'test-results/05-activity.png' });
  await page.reload();
  await page.locator('.wh-kpi').first().waitFor();
  check('재실행 시 가상 데이터 초기화', (await page.locator('.wh-kpi').first().innerText()).includes('24'));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/06-mobile.png' });
  check('모바일 화면 가로 넘침 없음', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await nav.getByRole('button', { name: 'IT 서비스', exact: true }).click();
  await page.locator('.wh-task-link').first().click();
  check('모바일 상세 화면', await page.getByRole('dialog').isVisible());
  await page.keyboard.press('Escape');
  await page.goto(`${url}?readonly=1`);
  await page.locator('.wh-kpi').first().waitFor();
  check('읽기 전용 등록 버튼 미렌더링', await page.getByRole('button', { name: '새 업무 등록', exact: true }).count() === 0);
  await nav.getByRole('button', { name: '전체 업무', exact: true }).click();
  await page.locator('.wh-task-link').first().click();
  check('읽기 전용 상태 변경·댓글 미렌더링', await page.getByRole('combobox', { name: '상태 변경' }).count() === 0 && await page.getByRole('textbox', { name: '댓글 입력' }).count() === 0);
  check('브라우저 오류 없음', errors.length === 0);
  check('외부 네트워크 호출 없음', remote.length === 0);
  await writeFile('test-results/ui-result.json', JSON.stringify({ passed: checks.length, checks, errors, remote }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, checks }, null, 2));
} finally { await browser.close(); }
