import { build } from 'esbuild';
import assert from 'node:assert/strict';
import { writeFile, mkdir } from 'node:fs/promises';
await mkdir('test-results', { recursive: true });
await build({ entryPoints: ['WorkHub/_service/demoService.ts'], outfile: 'test-results/service.mjs', bundle: true, platform: 'node', format: 'esm' });
const { DemoService } = await import('../test-results/service.mjs');
const service = new DemoService('김민서', false);
const checks = [];
const input = { title: '검증용 구매 요청', description: '단위 검증을 위한 가상 구매 요청입니다.', category: '구매·지출', department: '경영지원', priority: '보통', dueDate: '2026-11-30', amount: 120000, vendor: '가상 거래처', service: '', impact: '개인' };
await assert.rejects(service.create({ ...input, amount: -1 })); checks.push('음수 금액 거부');
await assert.rejects(service.create({ ...input, amount: 1000000001 })); checks.push('금액 상한 검증');
await assert.rejects(service.create({ ...input, dueDate: '2026-02-30' })); checks.push('존재하지 않는 날짜 거부');
await assert.rejects(service.create({ ...input, category: 'IT 서비스', service: '' })); checks.push('IT 대상 서비스 필수 검증');
await assert.rejects(service.create({ ...input, vendor: ' ' })); checks.push('구매 거래처 필수 검증');
await assert.rejects(service.changeStatus('WH-invalid', '완료')); checks.push('업무 ID 형식 검증');
await assert.rejects(service.changeStatus('WH-9999', '완료')); checks.push('미존재 ID 거부');
const id = await service.create(input);
const before = await service.read();
await service.changeStatus(id, '완료');
const after = await service.read();
assert.equal(after.items.find(item => item.id === id).progress, 100);
assert.equal(after.logs.length, before.logs.length + 1); checks.push('상태·진행률·활동 기록 일관성');
await service.changeStatus(id, '완료');
assert.equal((await service.read()).logs.length, after.logs.length); checks.push('동일 상태 변경 로그 중복 방지');
service.readOnly = true;
await assert.rejects(service.create(input));
await assert.rejects(service.comment(id, '테스트 댓글'));
await assert.rejects(service.changeStatus(id, '대기'));
await assert.rejects(service.reset()); checks.push('읽기 전용 모드의 모든 데모 변경 작업 거부');
await writeFile('test-results/domain-result.json', JSON.stringify({ passed: checks.length, checks }, null, 2));
console.log(JSON.stringify({ passed: checks.length, checks }, null, 2));
